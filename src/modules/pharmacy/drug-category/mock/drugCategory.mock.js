export const drugCategoryStatistics = {
    total:
        drugCategoryList.length,

    active:
        drugCategoryList.filter(
            (item) =>
                item.status ===
                "Active"
        ).length,

    inactive:
        drugCategoryList.filter(
            (item) =>
                item.status ===
                "Inactive"
        ).length,

    used:
        drugCategoryList.filter(
            (item) =>
                item.drugCount > 0
        ).length,

    unused:
        drugCategoryList.filter(
            (item) =>
                item.drugCount === 0
        ).length,

    root:
        drugCategoryList.filter(
            (item) =>
                item.parentCategoryId ===
                null
        ).length,

    child:
        drugCategoryList.filter(
            (item) =>
                item.parentCategoryId !==
                null
        ).length,
};


